-- 1. Quarter / whole-year targets ------------------------------------------
create table if not exists public.qy_targets (
  id                              bigint generated by default as identity primary key,
  level                           text not null check (level in ('PO', 'District')),
  year                            int  not null,                                   -- academic year start
  period                          text not null check (period in ('Q1', 'Q2', 'Q3', 'Q4', 'FY')),
  po_id                           text,
  po_name                         text,
  district                        text,
  story_telling                   numeric,
  poetry_recitation               numeric,
  creative_writing                numeric,
  spoken_english                  numeric,
  spelling_bee                    numeric,
  morning_assembly                numeric,
  st_streak                       numeric,
  pr_streak                       numeric,
  cw_streak                       numeric,
  se_streak                       numeric,
  sb_streak                       numeric,
  kathawli                        numeric,
  online_unique_teachers          numeric,
  online_unique_schools           numeric,
  posts_per_teacher               numeric,
  star_teachers                   numeric,
  teachers_using_expert_coupon    numeric,
  pom_transformed_clusters        numeric,
  blocks_with_recognition_events  numeric,
  district_recognition_event      numeric,
  teachers_recognized             numeric,
  cluster_heads_recognized        numeric,
  updated_by                      text,
  updated_at                      timestamptz not null default now()
);
create index if not exists qy_targets_period_idx on public.qy_targets (year, period, level);

-- 2 + 3. Quarter / whole-year copies of the Vinoba and Staff Connect tables + views
do $$
declare
  src   text;
  dst   text;
  vsrc  text;
  vdst  text;
  def   text;
  opts  text[];
  pairs text[][] := array[array['vinoba_data', 'vinoba_qy_data', 'vinoba_v', 'vinoba_qy_v'],
                          array['staffconnect_data', 'staffconnect_qy_data', 'staffconnect_v', 'staffconnect_qy_v']];
  i int;
begin
  for i in 1 .. array_length(pairs, 1) loop
    src := pairs[i][1]; dst := pairs[i][2]; vsrc := pairs[i][3]; vdst := pairs[i][4];

    -- table: same columns, defaults and identity as the monthly table (no rows, no constraints copied)
    if to_regclass('public.' || dst) is null then
      execute format('create table public.%I (like public.%I including defaults including identity including generated)', dst, src);
    end if;
    execute format('alter table public.%I add column if not exists period text', dst);
    if exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = dst and column_name = 'id')
       and not exists (select 1 from pg_constraint where conrelid = ('public.' || dst)::regclass and contype = 'p') then
      execute format('alter table public.%I add primary key (id)', dst);
    end if;
    execute format('create index if not exists %I on public.%I (year, week)', dst || '_period_idx', dst);

    -- view: the monthly view's own definition, reading the new table instead
    def := pg_get_viewdef(('public.' || vsrc)::regclass, false);
    select reloptions into opts from pg_class where oid = ('public.' || vsrc)::regclass;
    if def !~* ('\m' || src || '\M') then
      raise exception '% does not read % the expected way. Definition: %', vsrc, src, def;
    end if;
    def := regexp_replace(def, '\m' || src || '\M', dst, 'gi');
    def := regexp_replace(def, ';\s*$', '');
    execute format('create or replace view public.%I as ', vdst) || def;
    if opts is not null then
      execute format('alter view public.%I set (', vdst) || array_to_string(opts, ', ') || ')';
    end if;

    -- access: same pattern as week_dates / week_removed
    execute format('alter table public.%I enable row level security', dst);
    execute format('drop policy if exists %I on public.%I', dst || ' read',   dst);
    execute format('drop policy if exists %I on public.%I', dst || ' insert', dst);
    execute format('drop policy if exists %I on public.%I', dst || ' update', dst);
    execute format('drop policy if exists %I on public.%I', dst || ' delete', dst);
    execute format('create policy %I on public.%I for select to anon, authenticated using (true)', dst || ' read', dst);
    execute format('create policy %I on public.%I for insert to anon, authenticated with check (true)', dst || ' insert', dst);
    execute format('create policy %I on public.%I for update to anon, authenticated using (true) with check (true)', dst || ' update', dst);
    execute format('create policy %I on public.%I for delete to anon, authenticated using (true)', dst || ' delete', dst);
    execute format('grant select, insert, update, delete on public.%I to anon, authenticated', dst);
    execute format('grant select on public.%I to anon, authenticated', vdst);
    raise notice '% and % ready', dst, vdst;
  end loop;
end $$;

-- identity sequences of the new tables (only when "id" is an identity column there)
do $$
declare t text;
begin
  foreach t in array array['vinoba_qy_data', 'staffconnect_qy_data', 'qy_targets'] loop
    if exists (select 1 from information_schema.columns
               where table_schema = 'public' and table_name = t and column_name = 'id' and is_identity = 'YES') then
      execute format('grant usage, select on sequence %s to anon, authenticated',
                     pg_get_serial_sequence('public.' || t, 'id'));
    end if;
  end loop;
end $$;

alter table public.qy_targets enable row level security;
drop policy if exists "qy_targets read"   on public.qy_targets;
drop policy if exists "qy_targets insert" on public.qy_targets;
drop policy if exists "qy_targets update" on public.qy_targets;
drop policy if exists "qy_targets delete" on public.qy_targets;
create policy "qy_targets read"   on public.qy_targets for select to anon, authenticated using (true);
create policy "qy_targets insert" on public.qy_targets for insert to anon, authenticated with check (true);
create policy "qy_targets update" on public.qy_targets for update to anon, authenticated using (true) with check (true);
create policy "qy_targets delete" on public.qy_targets for delete to anon, authenticated using (true);
grant select, insert, update, delete on public.qy_targets to anon, authenticated;

commit;

-- let the API see the new tables and views straight away
notify pgrst, 'reload schema';

