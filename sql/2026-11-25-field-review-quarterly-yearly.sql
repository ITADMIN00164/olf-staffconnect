-- Run ONCE in the Supabase SQL editor of the "Field Team Review System"
-- project (xljnhbexevetzgaaehqc), BEFORE using the new tabs and uploads.
--
-- Adds only. No existing table, view or row is changed.
--
--   1. qy_targets             G2 · G3 targets per quarter / whole year,
--                             one row per PO (level 'PO') or per district (level 'District').
--   2. vinoba_qy_data         Vinoba Block Status Report uploaded for a quarter / whole year.
--      vinoba_qy_v            Same columns and rules as vinoba_v (block_key etc.), built from
--                             vinoba_v's own definition so both always match.
--   3. staffconnect_qy_data   Staff Connect event report for a quarter / whole year.
--      staffconnect_qy_v      Same as staffconnect_v (district_key, block_key ...).
--
-- How a period is stored in the *_qy_data tables (same columns as the monthly tables):
--   year   = academic year start (2026 = 2026-27)
--   week   = 1, 2, 3, 4 for Q1-Q4 · 9 for the whole year
--   month  = first month of the period (Q1 6 · Q2 9 · Q3 12 · Q4 3 · whole year 6)
--   period = 'Q1' .. 'Q4' or 'FY' (for reading the table by eye)
--
-- Quarterly / Whole Year review answers go into review_responses like Weekly and Monthly,
-- with their own period codes: <year>9<q>00 for a quarter (20269100 = 2026-27 Q1)
-- and <year>9900 for the whole year. Nothing to create for that.
--
-- Note: Staff Connect talks to Supabase with the anon key (login is Firebase), so
-- "itadmin only" for uploads is enforced in the page, same as the other Admin features.
--
-- Safe to run twice. If any step fails, nothing is applied (one transaction).
-- =====================================================================

