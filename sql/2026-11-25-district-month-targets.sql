-- =====================================================================
-- Field Review System — monthly DISTRICT targets  (25-Nov-2026)
-- Run ONCE in the Supabase SQL editor of the "Field Team Review System"
-- project (xljnhbexevetzgaaehqc), before uploading district targets
-- (Admin > G2 · G3 · G5 Targets > Level: District).
--
-- Adds one table. Nothing existing is changed: g1_g2_g3_target_sheet keeps the PO rows.
--
--   district_targets   one row per district per month, same target columns as the PO file.
--   Used by the Monthly review for District, PM and DM views. A district with no row
--   for the month falls back to adding up its PO rows (the old rule), so months
--   uploaded earlier keep showing the same numbers.
--
-- Note: Staff Connect talks to Supabase with the anon key (login is Firebase), so
-- "itadmin only" for uploads is enforced in the page, same as the other Admin features.
-- Safe to run twice.
-- =====================================================================

begin;

create table if not exists public.district_targets (
  id  bigint generated by default as identity primary key,
  year        int  not null,
  month       int  not null check (month between 1 and 12),
  district    text not null,
  story_telling                   numeric,
  poetry_recitation               numeric,
  creative_writing                numeric,
  spoken_english                  numeric,
  spelling_bee                    numeric,
  morning_assembly                numeric,
  st_streak                       numeric,
  pr_streak                       numeric,
  cw_streak                       numeric,
  se_streak                       numeric,
  sb_streak                       numeric,
  kathawli                        numeric,
  online_unique_teachers          numeric,
  online_unique_schools           numeric,
  posts_per_teacher               numeric,
  star_teachers                   numeric,
  teachers_using_expert_coupon    numeric,
  pom_transformed_clusters        numeric,
  blocks_with_recognition_events  numeric,
  district_recognition_event      numeric,
  teachers_recognized             numeric,
  cluster_heads_recognized        numeric,
  school_visits                   numeric,
  cluster_visits                  numeric,
  officials_visits                numeric,
  case_study                      numeric,
  compliance_pct                  numeric,
  updated_by  text,
  updated_at  timestamptz not null default now()
);
create index if not exists district_targets_month_idx on public.district_targets (year, month);

alter table public.district_targets enable row level security;
drop policy if exists "district_targets read"   on public.district_targets;
drop policy if exists "district_targets insert" on public.district_targets;
drop policy if exists "district_targets update" on public.district_targets;
drop policy if exists "district_targets delete" on public.district_targets;
create policy "district_targets read"   on public.district_targets for select to anon, authenticated using (true);
create policy "district_targets insert" on public.district_targets for insert to anon, authenticated with check (true);
create policy "district_targets update" on public.district_targets for update to anon, authenticated using (true) with check (true);
create policy "district_targets delete" on public.district_targets for delete to anon, authenticated using (true);
grant select, insert, update, delete on public.district_targets to anon, authenticated;

commit;

notify pgrst, 'reload schema';

